const getColumns = (columns, sortObj = {}) => {
    return columns.map(item => {
        const dataKey = item.dataKey?.toLowerCase();
        return {
            width: item.width,
            showTooltip: item.showTooltip || false,
            tooltipIconName: item.tooltipIcon || "",
            tooltipContent: item.tooltipText || "",
            enableSorting: !item.disableSort,
            tableHead: <span>{item.label}</span>,
            tableHeaderClick: () => {
                // const sortMethod = sortObj.method;
                // sortMethod({ sortBy: SORT_KEY_MAPPING[dataKey] });
            },
            sortOrder: "desc"
        };
    });
}

const renderTableRow = (rowsConfig, visiblePageData) => {
    const rows = visiblePageData.map(item => {
        // const ctaStatus = fetchCtaState(this.props.activeChannel, item.status);
        const isReconnectInprogress = false;
        return {
            rowsData: rowsConfig.map((config, index) => ({
                className: rowsConfig.length - 1 === index ? "last-column" + (isReconnectInprogress ? " reconnection-in-progress" : "") : "",
                rowValue: <span>{config.cellRenderer({ ...config, rowData: item })}</span>,
                width: config.width,
                dataKey: config.dataKey
            }))
        };
    });
    return rows;
}

